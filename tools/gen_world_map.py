#!/usr/bin/env python3
"""Write src/world_map.h: a 64x32 equirectangular land mask (1 = land) for the space-station map.

  pip install global-land-mask      # github.com/toddkarin/global-land-mask (MIT), GLOBE 1 km land data (NOAA)
  python3 tools/gen_world_map.py

Each map pixel is land when at least 6 of 16 samples inside it are land.
"""
import os
from global_land_mask import globe

W, H = 64, 32
rows = []
for y in range(H):
    bits = 0
    for x in range(W):
        n = 0
        for dy in range(4):
            for dx in range(4):
                lat = 90 - (y + (dy + 0.5) / 4) * 180 / H
                lon = -180 + (x + (dx + 0.5) / 4) * 360 / W
                n += bool(globe.is_land(lat, lon))
        if n >= 6:
            bits |= 1 << (63 - x)
    rows.append(bits)
out = ["// Generated by tools/gen_world_map.py from global-land-mask (MIT; GLOBE land data, NOAA). Row 0 = 90N,",
       "// column 0 = 180W; bit 63 is the left-most pixel.",
       "#pragma once", "#include <stdint.h>", "static const uint64_t WORLD_LAND[32] = {"]
out += ["  0x%016XULL," % r for r in rows]
out += ["};", ""]
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "world_map.h")
open(dst, "w").write("\n".join(out))
print("wrote", os.path.normpath(dst))
