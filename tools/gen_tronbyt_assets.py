#!/usr/bin/env python3
"""Turn artwork from the tronbyt/apps repo (Apache-2.0) into src/tronbyt_assets.h.

  git clone --depth 1 --filter=blob:none --sparse https://github.com/tronbyt/apps
  cd apps && git sparse-checkout set apps/nixelclock apps/bigclock apps/yulelog
  python3 -I tools/gen_tronbyt_assets.py /path/to/apps/apps

What it takes (see NOTICE for credits):
  nixelclock/images/round_brighter  - nixie-tube digit photos, 15x15, plus the 4x15 separator  (saltedlolly)
  bigclock/images                   - 13x32 beveled segment digits + 4x14 colon, used as masks  (Joey Hoer)
  yulelog/images/animation.gif      - 64x32 fireplace loop (Tidbyt; footage from Pexels video 6507518)
"""
import os
import sys

from PIL import Image


def rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def img565(path):
    im = Image.open(path).convert("RGB")
    w, h = im.size
    return w, h, [rgb565(*im.getpixel((x, y))) for y in range(h) for x in range(w)]


def mask_rows(path):
    # black background, transparent foreground -> 1 where the digit is lit
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    rows = []
    for y in range(h):
        v = 0
        for x in range(w):
            if im.getpixel((x, y))[3] < 128:
                v |= 1 << (w - 1 - x)
        rows.append(v)
    return w, h, rows


def arr(name, ctype, vals, per=16, fmt="0x%04X"):
    out = ["static const %s %s[%d] PROGMEM = {" % (ctype, name, len(vals))]
    for i in range(0, len(vals), per):
        out.append("  " + ", ".join(fmt % v for v in vals[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


def main(root):
    parts = [
        "// Generated by tools/gen_tronbyt_assets.py from github.com/tronbyt/apps (Apache-2.0). See NOTICE.",
        "#pragma once",
        "#include <stdint.h>",
        "#ifndef PROGMEM",
        "#define PROGMEM",
        "#endif",
        "",
    ]
    nix = os.path.join(root, "nixelclock/images/round_brighter")
    px = []
    for d in range(10):
        w, h, p = img565(os.path.join(nix, "%d.png" % d))
        assert (w, h) == (15, 15)
        px += p
    parts.append("// Nixel Clock tubes by saltedlolly: 10 digits, 15x15 RGB565 each")
    parts.append(arr("NIXEL_DIGITS", "uint16_t", px))
    w, h, p = img565(os.path.join(nix, "sep.png"))
    assert (w, h) == (4, 15)
    parts.append(arr("NIXEL_SEP", "uint16_t", p))

    big = os.path.join(root, "bigclock/images")
    rows = []
    for d in range(10):
        w, h, r = mask_rows(os.path.join(big, "number_%d.png" % d))
        assert (w, h) == (13, 32)
        rows += r
    parts.append("// Big Clock digits by Joey Hoer: 10 digits x 32 rows, 13 bits per row (bit 12 = left)")
    parts.append(arr("BIG_DIGITS", "uint16_t", rows))
    w, h, r = mask_rows(os.path.join(big, "sep.png"))
    assert (w, h) == (4, 14)
    parts.append(arr("BIG_SEP", "uint8_t", r, fmt="0x%02X"))

    gif = open(os.path.join(root, "yulelog/images/animation.gif"), "rb").read()
    parts.append("// Yule Log by Tidbyt; video by Pexels (pexels.com/video/6507518). 64x32 animated GIF")
    parts.append(arr("YULE_GIF", "uint8_t", list(gif), per=24, fmt="0x%02X"))
    parts.append("")
    dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "tronbyt_assets.h")
    with open(dst, "w") as f:
        f.write("\n".join(parts))
    print("wrote", os.path.normpath(dst), "(gif %d bytes)" % len(gif))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "/tmp/tapps/apps")
