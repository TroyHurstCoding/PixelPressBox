# PlatformIO pre-build step: gzips the phone page in src/webpage.h into a byte array the web server sends
# as a gzip-compressed response (about a quarter of the flash, and quicker to load on a phone).
# src/webpage.h stays the file to edit; the generated header lives in the build folder.
import gzip
import os
import re

Import("env")  # noqa: F821  (provided by PlatformIO)

src = os.path.join(env.subst("$PROJECT_DIR"), "src", "webpage.h")  # noqa: F821
out_dir = os.path.join(env.subst("$BUILD_DIR"), "generated")  # noqa: F821
out = os.path.join(out_dir, "webpage_gz.h")

page = re.search(r'R"HTML\((.*)\)HTML"', open(src, encoding="utf-8").read(), re.S).group(1)
data = gzip.compress(page.encode("utf-8"), compresslevel=9, mtime=0)
rows = ",\n".join(",".join(str(b) for b in data[i:i + 32]) for i in range(0, len(data), 32))
text = ("// generated by tools/gzip_webpage.py from src/webpage.h - do not edit\n#pragma once\n#include <stdint.h>\n"
        "static const uint8_t WEB_PAGE_GZ[%d] = {\n%s};\n" % (len(data), rows))

os.makedirs(out_dir, exist_ok=True)
if not os.path.exists(out) or open(out).read() != text:  # rewrite only on change, so nothing recompiles needlessly
    open(out, "w").write(text)
print("webpage: %d bytes -> %d gzipped" % (len(page), len(data)))
env.Append(CPPPATH=[out_dir])  # noqa: F821
